import { expect, test } from '@playwright/test'
import path from 'node:path'
import fs from 'node:fs'
import { launchAgentApp, listen, startScriptedModel } from './helpers/scripted-agent'

const viteCli = () => path.resolve(process.env.PI_TEST_VITE_CLI || 'node_modules/vite/bin/vite.js').replace(/\\/g, '/')

test('terminal keeps a readable prompt after running and stopping Vite', async () => {
  const model = startScriptedModel(() => ({ text: 'ok' }), [])
  const agent = await launchAgentApp(await listen(model), { config: { rightPanelPrefs: { files: true, terminal: true, git: true, run: true, browser: false }, rightPanelCollapsed: false } })
  fs.writeFileSync(path.join(agent.project, 'index.html'), '<html><body>Vite test</body></html>')
  try {
    await agent.newSession()
    await agent.win.getByRole('button', { name: 'Expand right panel' }).click()
    await agent.win.getByRole('tab', { name: 'Terminal', exact: true }).click()
    const panel = agent.win.locator('.terminal-drawer')
    await panel.getByRole('button', { name: 'New terminal', exact: true }).first().click()
    const terminal = panel.locator('.xterm').first()
    await expect(terminal).toBeVisible()
    await expect(terminal.locator('.xterm-rows')).toContainText('> ', { timeout: 30000 })
    await terminal.click()
    const vite = viteCli()
    await agent.win.keyboard.insertText(`unset FORCE_COLOR NO_COLOR; node '${vite}' --host 127.0.0.1 --port 0`)
    await agent.win.keyboard.press('Enter')
    await expect(terminal).toContainText('VITE', { timeout: 30000 })
    await agent.app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1400, 550))
    await agent.win.waitForTimeout(1000)
    await agent.app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1400, 900))
    await agent.win.waitForTimeout(1000)
    await agent.win.getByRole('tab', { name: 'Files', exact: true }).click()
    await agent.win.getByRole('tab', { name: 'Terminal', exact: true }).click()
    await terminal.click()
    await agent.win.keyboard.insertText('r')
    await agent.win.keyboard.press('Enter')
    await agent.win.waitForTimeout(2000)
    await agent.win.keyboard.press('Control+c')
    await agent.win.waitForTimeout(700)
    await agent.win.keyboard.insertText(`node '${vite}' --host 127.0.0.1 --port 0`)
    await agent.win.keyboard.press('Enter')
    await agent.win.waitForTimeout(2500)
    await agent.win.keyboard.press('Control+c')
    await agent.win.waitForTimeout(700)
    await agent.win.keyboard.insertText('echo DISPLAY_CHECK')
    await agent.win.keyboard.press('Enter')
    await expect(terminal).toContainText('DISPLAY_CHECK', { timeout: 30000 })
  } finally {
    await agent.win.getByRole('button', { name: 'Close terminal', exact: true }).first().click({ timeout: 3000 }).catch(() => undefined)
    await agent.close()
    model.close()
  }
})

test('one-click Vite launch maintains cursor position after termination', async () => {
  const model = startScriptedModel(() => ({ text: 'ok' }), [])
  const agent = await launchAgentApp(await listen(model), { config: { rightPanelPrefs: { files: true, terminal: true, git: true, run: true, browser: false }, rightPanelCollapsed: false } })
  const vite = viteCli()
  fs.writeFileSync(path.join(agent.project, 'index.html'), '<html><body>Vite test</body></html>')
  fs.mkdirSync(path.join(agent.project, '.vscode'))
  fs.writeFileSync(path.join(agent.project, '.vscode', 'tasks.json'), JSON.stringify({ version: '2.0.0', tasks: [{ label: 'Backend', command: 'node', args: ['-e', 'setInterval(() => {}, 1000)'] }, { label: 'Client', command: 'node', args: ['-e', 'setInterval(() => {}, 2000)'] }, { label: 'Vite display', command: 'env', args: ['-u', 'FORCE_COLOR', '-u', 'NO_COLOR', 'node', vite, '--host', '127.0.0.1', '--port', '0'] }, { label: 'Run', dependsOn: ['Backend', 'Client', 'Vite display'], group: { kind: 'build', isDefault: true } }] }))
  try {
    await agent.newSession()
    await agent.win.getByRole('button', { name: 'Expand right panel' }).click()
    await agent.win.getByRole('tab', { name: 'Terminal', exact: true }).click()
    const panel = agent.win.locator('.terminal-drawer')
    await agent.win.evaluate(() => {
      const { ipcClient } = (window as unknown as { __piE2E: { ipcClient: { invoke: (channel: string, data: unknown) => Promise<unknown> } } }).__piE2E
      const original = ipcClient.invoke.bind(ipcClient)
      ipcClient.invoke = (channel, data) => channel === 'terminal.resize'
        ? new Promise((resolve, reject) => setTimeout(() => original(channel, data).then(resolve, reject), 4500))
        : original(channel, data)
    })
    await panel.getByRole('button', { name: 'Run', exact: true }).click()
    await expect(panel.locator('.xterm')).toHaveCount(3)
    const terminal = panel.locator('.xterm').last()
    await expect(terminal).toBeVisible()
    await agent.win.waitForTimeout(3800)
    await expect(terminal).not.toContainText('VITE')
    await expect(terminal).toContainText('VITE', { timeout: 30000 })
    await agent.win.waitForTimeout(4000)
    await panel.getByRole('button', { name: 'Close terminal', exact: true }).first().click()
    await panel.getByRole('button', { name: 'Close terminal', exact: true }).first().click()
    await agent.win.waitForTimeout(2500)
    await terminal.click()
    for (let index = 0; index < 5; index++) await agent.win.keyboard.press('Enter')
    await panel.getByRole('button', { name: /Clear terminal display/ }).click()
    await expect(terminal).not.toContainText('VITE')
    await agent.win.keyboard.insertText('h')
    await agent.win.keyboard.press('Enter')
    await expect(terminal).toContainText('Shortcuts', { timeout: 10000 })
    await agent.win.keyboard.press('Control+c')
    await agent.win.waitForTimeout(1000)
    await agent.win.keyboard.insertText('echo ONE_CLICK_FINISHED')
    await agent.win.keyboard.press('Enter')
    await expect(terminal.locator('.xterm-rows > div').filter({ hasText: /^ONE_CLICK_FINISHED\s*$/ })).toHaveCount(1, { timeout: 30000 })
    const rows = await terminal.locator('.xterm-rows > div').allTextContents()
    const helpLine = rows.findIndex((line) => line.includes('Shortcuts'))
    const commandLine = rows.findIndex((line) => line.includes('echo ONE_CLICK_FINISHED'))
    expect(helpLine).toBeGreaterThanOrEqual(0)
    expect(commandLine).toBeGreaterThan(helpLine)
  } finally {
    await agent.win.getByRole('button', { name: 'Close terminal', exact: true }).first().click({ timeout: 3000 }).catch(() => undefined)
    await agent.close()
    model.close()
  }
})


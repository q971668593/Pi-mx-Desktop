import { expect, test } from '@playwright/test'
import fs from 'node:fs'
import path from 'node:path'
import { launchAgentApp, listen, startScriptedModel } from './helpers/scripted-agent'

test('keeps unsaved drafts across tabs and searches files throughout the project', async () => {
  const model = startScriptedModel(() => ({ text: 'ok' }), [])
  const agent = await launchAgentApp(await listen(model), { config: { rightPanelPrefs: { files: true, terminal: true, git: true, run: true, browser: false }, rightPanelCollapsed: false } })
  fs.writeFileSync(path.join(agent.project, 'first.txt'), 'original first')
  fs.writeFileSync(path.join(agent.project, 'second.txt'), 'original second')
  fs.writeFileSync(path.join(agent.project, '.hidden'), 'hidden')
  fs.writeFileSync(path.join(agent.project, 'example.ts'), 'const message: string = "hello";')
  fs.mkdirSync(path.join(agent.project, 'nested'))
  fs.writeFileSync(path.join(agent.project, 'nested', 'deep-unique.txt'), 'nested text')
  const win = agent.win
  try {
    await agent.newSession()
    await win.getByRole('button', { name: 'Expand right panel' }).click()
    await win.getByRole('tab', { name: 'Files' }).click()
    await expect(win.getByRole('button', { name: '.hidden', exact: true })).toBeVisible()
    await win.getByRole('button', { name: 'first.txt', exact: true }).click()
    const editor = win.locator('.cm-content[contenteditable="true"]')
    await editor.click()
    await win.keyboard.press('Control+A')
    await win.keyboard.insertText('unsaved first')
    const explorer = win.getByRole('button', { name: /file tree/i })
    if ((await explorer.getAttribute('aria-label')) === 'Expand file tree') await explorer.click()
    await win.getByRole('button', { name: 'second.txt', exact: true }).click()
    await expect(editor).toContainText('original second')
    await win.getByRole('tab', { name: /first\.txt/ }).click()
    await expect(editor).toContainText('unsaved first')
    await win.getByRole('button', { name: 'Save', exact: true }).click()
    await expect.poll(() => fs.readFileSync(path.join(agent.project, 'first.txt'), 'utf8')).toBe('unsaved first')
    if ((await explorer.getAttribute('aria-label')) === 'Expand file tree') await explorer.click()
    const search = win.locator('.files-search input')
    await search.fill('deep-unique')
    await expect(win.getByRole('button', { name: /deep-unique\.txt/ })).toBeVisible()
    await win.getByRole('button', { name: /deep-unique\.txt/ }).click()
    await expect(editor).toContainText('nested text')
    await editor.click()
    await win.keyboard.press('Control+f')
    await expect(win.locator('.cm-search input').first()).toBeVisible()
    await win.keyboard.press('Escape')
    if ((await explorer.getAttribute('aria-label')) === 'Expand file tree') await explorer.click()
    await search.fill('example.ts')
    await win.getByRole('button', { name: /example\.ts/ }).click()
    await expect(editor.locator('.cm-line span').first()).toBeVisible()
  } finally {
    await agent.close()
    model.close()
  }
})

test('pins, closes, and reorders file tabs while limiting unpinned files', async () => {
  const model = startScriptedModel(() => ({ text: 'ok' }), [])
  const agent = await launchAgentApp(await listen(model), { config: { rightPanelPrefs: { files: true, terminal: true, git: true, run: true, browser: false }, rightPanelCollapsed: false } })
  for (let index = 1; index <= 7; index++) fs.writeFileSync(path.join(agent.project, `file-${index}.txt`), `file ${index}`)
  const win = agent.win
  try {
    await agent.newSession()
    await win.getByRole('button', { name: 'Expand right panel' }).click()
    await win.getByRole('tab', { name: 'Files' }).click()
    const openFile = async (index: number) => {
      const tree = win.getByRole('button', { name: /file tree/i })
      if ((await tree.getAttribute('aria-label')) === 'Expand file tree') await tree.click()
      await win.getByRole('button', { name: `file-${index}.txt`, exact: true }).click()
    }
    await openFile(1)
    await win.locator('.files-preview-tab').filter({ hasText: 'file-1.txt' }).click({ button: 'right' })
    await win.getByRole('button', { name: 'Pin tab' }).click()
    for (let index = 2; index <= 7; index++) await openFile(index)
    const tabs = win.locator('.files-preview-tab')
    await expect(tabs).toHaveCount(6)
    await expect(tabs.filter({ hasText: 'file-1.txt' })).toBeVisible()
    await expect(tabs.filter({ hasText: 'file-2.txt' })).toHaveCount(0)
    const last = tabs.filter({ hasText: 'file-7.txt' })
    await last.getByRole('button', { name: 'Close tab' }).click({ force: true })
    await expect(tabs).toHaveCount(5)
    await tabs.filter({ hasText: 'file-6.txt' }).scrollIntoViewIfNeeded()
    const source = await tabs.filter({ hasText: 'file-6.txt' }).boundingBox()
    const target = await tabs.filter({ hasText: 'file-5.txt' }).boundingBox()
    if (!source || !target) throw new Error('File tab bounds not available')
    await win.mouse.move(source.x + source.width / 2, source.y + source.height / 2)
    await win.mouse.down()
    await win.mouse.move(target.x + target.width / 2, target.y + target.height / 2, { steps: 5 })
    await win.mouse.up()
    await expect(tabs.nth(3)).toContainText('file-6.txt')
  } finally {
    await agent.close()
    model.close()
  }
})

test('finds text in preview, manipulates images and creates files from the tree background', async () => {
  const model = startScriptedModel(() => ({ text: 'ok' }), [])
  const agent = await launchAgentApp(await listen(model), { config: { rightPanelPrefs: { files: true, terminal: true, git: true, run: true, browser: false }, rightPanelCollapsed: false } })
  fs.writeFileSync(path.join(agent.project, 'picture.png'), Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+/p9sAAAAASUVORK5CYII=', 'base64'))
  const win = agent.win
  try {
    await agent.newSession()
    await win.getByRole('button', { name: 'Expand right panel' }).click()
    await win.getByRole('tab', { name: 'Files' }).click()
    await win.getByRole('button', { name: 'README.md', exact: true }).click()
    await win.keyboard.press('Control+f')
    const find = win.getByPlaceholder('Find', { exact: true })
    await find.fill('demo')
    await expect(win.locator('[data-file-find]')).toContainText('1/1')
    await win.getByRole('button', { name: 'Close search' }).click()
    const tree = win.getByRole('button', { name: /file tree/i })
    if ((await tree.getAttribute('aria-label')) === 'Expand file tree') await tree.click()
    await win.getByRole('button', { name: 'picture.png', exact: true }).click()
    const image = win.getByRole('img', { name: 'picture.png' })
    await image.locator('..').hover()
    await win.mouse.wheel(0, -200)
    await expect(image).toHaveAttribute('style', /scale\(1\.12\)/)
    const bounds = await image.boundingBox()
    if (!bounds) throw new Error('Image bounds not available')
    await win.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2)
    await win.mouse.down()
    await win.mouse.move(bounds.x + bounds.width / 2 + 25, bounds.y + bounds.height / 2 + 15)
    await win.mouse.up()
    await expect(image).toHaveAttribute('style', /translate\(25px, 15px\)/)
    if ((await tree.getAttribute('aria-label')) === 'Expand file tree') await tree.click()
    await win.locator('.files-explorer-rail').click({ button: 'right', position: { x: 20, y: 200 } })
    await win.getByRole('button', { name: 'New file', exact: true }).click()
    const dialog = win.getByRole('dialog', { name: 'New file' })
    await dialog.getByRole('textbox').fill('new-from-background.txt')
    await dialog.getByRole('textbox').press('Enter')
    await expect.poll(() => fs.existsSync(path.join(agent.project, 'new-from-background.txt'))).toBe(true)
  } finally {
    await agent.close()
    model.close()
  }
})

test('remembers the right panel and file tabs separately for each project', async () => {
  const model = startScriptedModel(() => ({ text: 'ok' }), [])
  const agent = await launchAgentApp(await listen(model), { config: { rightPanelPrefs: { files: true, terminal: true, git: true, run: true, browser: false }, rightPanelCollapsed: false } })
  const other = path.join(agent.home, 'code', 'other')
  fs.mkdirSync(other, { recursive: true })
  fs.mkdirSync(path.join(agent.project, 'folder-a'))
  fs.writeFileSync(path.join(agent.project, 'folder-a', 'inside.txt'), 'inside')
  fs.writeFileSync(path.join(agent.project, 'project-a.txt'), 'first project')
  fs.writeFileSync(path.join(other, 'project-b.txt'), 'second project')
  const win = agent.win
  const switchProject = (workspace: string) => win.evaluate((value) => {
    const debug = (window as unknown as { __piE2E: { useUIStore: { getState: () => { setWorkspace: (path: string) => void } } } }).__piE2E
    debug.useUIStore.getState().setWorkspace(value)
  }, workspace)
  try {
    await agent.newSession()
    await win.getByRole('button', { name: 'Expand right panel' }).click()
    await win.getByRole('tab', { name: 'Files' }).click()
    await win.locator('[title="folder-a"]').first().click()
    await expect(win.getByRole('button', { name: 'inside.txt', exact: true })).toBeVisible()
    await win.getByRole('button', { name: 'project-a.txt', exact: true }).click()
    await switchProject(other)
    await expect(win.getByRole('tab', { name: 'Run', exact: true })).toHaveAttribute('aria-selected', 'true')
    await win.getByRole('tab', { name: 'Files' }).click()
    await win.getByRole('button', { name: 'project-b.txt', exact: true }).click()
    await expect(win.locator('.files-preview-tab')).toContainText(['project-b.txt'])
    await switchProject(agent.project)
    await expect(win.getByRole('tab', { name: 'Files', exact: true })).toHaveAttribute('aria-selected', 'true')
    await expect(win.locator('.files-preview-tab')).toContainText(['project-a.txt'])
    const tree = win.getByRole('button', { name: /file tree/i })
    if ((await tree.getAttribute('aria-label')) === 'Expand file tree') await tree.click()
    await expect(win.getByRole('button', { name: 'inside.txt', exact: true })).toBeVisible()
    await switchProject(other)
    await expect(win.locator('.files-preview-tab')).toContainText(['project-b.txt'])
  } finally {
    await agent.close()
    model.close()
  }
})
